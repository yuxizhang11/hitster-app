import type { Category, Song } from './types';

type Raw = [title: string, artist: string, year: number];

function build(id: string, name: string, emoji: string, colors: [string, string], raw: Raw[]): Category {
  const songs: Song[] = raw.map(([title, artist, year]) => ({
    id: `${id}:${title}:${artist}`.toLowerCase(),
    title,
    artist,
    year,
    category: id,
  }));
  return { id, name, emoji, colors, songs };
}

